import type { ChannelConfig, ChannelContentSource, PlaybackMode } from '../../scheduler/channel-manager/contracts/types';
import type { ChannelStructuralBase } from '../../scheduler/channel-manager/contracts/ChannelDurability';
import { sameActiveMedia, type ChannelDirectoryPorts, type ActiveMediaIdentity } from './ChannelDirectoryPorts';

export type DirectoryFilter = 'all' | 'custom' | 'generated';
export type DirectoryMode = 'browse' | 'select' | 'reorder';
export type ChannelHealth =
    | { kind: 'unchecked' }
    | { kind: 'loading' }
    | { kind: 'healthy' | 'offair' | 'stale' | 'failed'; checkedAt: number; detail: string };

export type DirectoryNotice = { kind: 'error' | 'saved-warning' | 'saved' | 'info'; text: string } | null;
export type DirectoryDeleteResult = { kind: 'not-saved' } | { kind: 'saved'; openGuide: boolean };

export interface DirectoryRow {
    channel: ChannelConfig;
    source: string;
    playback: string;
    generated: boolean;
    health: ChannelHealth;
}

const MODE_LABEL: Record<PlaybackMode, string> = {
    sequential: 'In order', shuffle: 'Mix it up', block: 'Mini marathon', random: 'Random',
};

export function sourceLabel(source: ChannelContentSource): string {
    switch (source.type) {
        case 'library': return source.libraryType === 'show' ? 'TV library' : 'Movie library';
        case 'collection': return `Collection · ${source.collectionName}`;
        case 'show': return `Show · ${source.showName}`;
        case 'playlist': return `Playlist · ${source.playlistName}`;
        case 'manual': return `${source.items.length} hand-picked program${source.items.length === 1 ? '' : 's'}`;
        case 'mixed': return `${source.sources.length} mixed source${source.sources.length === 1 ? '' : 's'}`;
    }
}

function isGenerated(channel: ChannelConfig): boolean {
    return channel.isAutoGenerated === true || channel.buildStrategy !== undefined;
}

export function projectDirectoryRows(channels: ChannelConfig[], filter: DirectoryFilter, query: string,
    health: ReadonlyMap<string, ChannelHealth>): DirectoryRow[] {
    const needle = query.trim().toLocaleLowerCase();
    return channels.filter(channel => {
        const generated = isGenerated(channel);
        return (filter === 'all' || (filter === 'generated') === generated)
            && (!needle || channel.name.toLocaleLowerCase().includes(needle) || String(channel.number).includes(needle));
    }).map(channel => ({
        channel, source: sourceLabel(channel.contentSource), playback: MODE_LABEL[channel.playbackMode],
        generated: isGenerated(channel), health: health.get(channel.id) ?? { kind: 'unchecked' },
    }));
}

function sameBase(a: ChannelStructuralBase, b: ChannelStructuralBase): boolean {
    return a.generation === b.generation && a.revision === b.revision;
}

function readable(kind: string): boolean {
    return kind === 'readable' || kind === 'readable-degraded' || kind === 'valid-empty';
}

export class ChannelDirectoryModel {
    readonly health = new Map<string, ChannelHealth>();
    filter: DirectoryFilter = 'all';
    query = '';
    mode: DirectoryMode = 'browse';
    selectedIds = new Set<string>();
    focusedChannelId: string | null = null;
    notice: DirectoryNotice = null;
    private reorderIds: string[] | null = null;
    private reorderNumberSlots: number[] | null = null;
    private reorderBase: ChannelStructuralBase | null = null;
    private readonly ports: ChannelDirectoryPorts;
    private readonly healthControllers = new Map<string, AbortController>();
    private healthBase: ChannelStructuralBase;
    private epoch = 0;

    constructor(ports: ChannelDirectoryPorts) { this.ports = ports; this.healthBase = ports.manager.getStructuralBase(); }

    get loadKind(): string { return this.ports.manager.getLastLoadOutcome().kind; }
    get canMutate(): boolean { return readable(this.loadKind); }
    get channels(): ChannelConfig[] { return this.ports.manager.getAllChannels().sort((a, b) => a.number - b.number); }
    get rows(): DirectoryRow[] {
        this.refreshHealthBase();
        const all = this.channels;
        const byId = new Map(all.map(channel => [channel.id, channel]));
        const channels = this.mode === 'reorder' && this.reorderIds
            ? this.reorderIds.map(id => byId.get(id)).filter((value): value is ChannelConfig => !!value)
            : all;
        return projectDirectoryRows(channels, this.filter, this.query, this.health);
    }
    get allSelectedChannels(): ChannelConfig[] { return this.channels.filter(ch => this.selectedIds.has(ch.id)); }
    get hasReorderChanges(): boolean {
        return this.reorderIds !== null && this.reorderIds.some((id, i) => id !== this.channels[i]?.id);
    }
    proposedNumber(id: string): number | null {
        if (!this.reorderIds || !this.reorderNumberSlots) return this.channels.find(ch => ch.id === id)?.number ?? null;
        const index = this.reorderIds.indexOf(id);
        return index < 0 ? null : this.reorderNumberSlots[index] ?? null;
    }

    setQuery(query: string): void { this.query = query; this.repairFocus(); }
    setFilter(filter: DirectoryFilter): void { this.filter = filter; this.repairFocus(); }
    setFocusedChannel(id: string | null): void { this.focusedChannelId = id; }
    private repairFocus(): void {
        if (this.focusedChannelId && !this.rows.some(row => row.channel.id === this.focusedChannelId)) {
            this.focusedChannelId = this.rows[0]?.channel.id ?? null;
        }
    }
    beginSelection(): void {
        if (this.mode === 'reorder') this.cancelReorder();
        this.mode = 'select'; this.selectedIds.clear(); this.notice = null;
    }
    toggleSelected(id: string): void {
        if (this.mode !== 'select' || !this.channels.some(ch => ch.id === id)) return;
        if (this.selectedIds.has(id)) this.selectedIds.delete(id); else this.selectedIds.add(id);
    }
    selectAllMatching(): void { for (const row of this.rows) this.selectedIds.add(row.channel.id); }
    clearSelection(): void { this.selectedIds.clear(); }
    cancelSelection(): void { this.selectedIds.clear(); this.mode = 'browse'; }
    beginReorder(): boolean {
        if (!this.canMutate) return false;
        if (this.query.trim() || this.filter !== 'all') {
            this.notice = { kind: 'info', text: 'Clear search and choose All before reordering every channel.' };
            return false;
        }
        const channels = this.channels;
        this.selectedIds.clear(); this.mode = 'reorder'; this.reorderIds = channels.map(ch => ch.id);
        this.reorderNumberSlots = channels.map(ch => ch.number);
        this.reorderBase = this.ports.manager.getStructuralBase(); this.notice = null;
        return true;
    }
    move(id: string, offset: number): boolean {
        if (!this.reorderIds) return false;
        const from = this.reorderIds.indexOf(id), to = from + offset;
        if (from < 0 || to < 0 || to >= this.reorderIds.length) return false;
        this.reorderIds.splice(from, 1); this.reorderIds.splice(to, 0, id);
        this.focusedChannelId = id;
        return true;
    }
    moveTo(id: string, targetIndex: number): boolean {
        if (!this.reorderIds || targetIndex < 0 || targetIndex >= this.reorderIds.length) return false;
        const from = this.reorderIds.indexOf(id);
        if (from < 0) return false;
        this.reorderIds.splice(from, 1); this.reorderIds.splice(targetIndex, 0, id);
        this.focusedChannelId = id;
        return true;
    }
    cancelReorder(): void {
        this.reorderIds = null; this.reorderNumberSlots = null; this.reorderBase = null;
        this.selectedIds.clear(); this.mode = 'browse'; this.notice = null;
    }

    async saveOrder(): Promise<boolean> {
        const ids = this.reorderIds, base = this.reorderBase;
        if (!ids || !base || !this.canMutate) return false;
        if (!sameBase(base, this.ports.manager.getStructuralBase())) {
            this.notice = { kind: 'error', text: 'The lineup changed. Cancel reorder and start again.' }; return false;
        }
        if (!this.hasReorderChanges) { this.cancelReorder(); return true; }
        const channels = this.channels, numberSlots = [...channels.map(ch => ch.number)].sort((a, b) => a - b);
        if (ids.length !== channels.length || numberSlots.some(n => !Number.isInteger(n) || n < 1 || n > 500)) {
            this.notice = { kind: 'error', text: 'The lineup cannot be reordered. Reload and try again.' }; return false;
        }
        const byId = new Map(channels.map(ch => [ch.id, ch]));
        const replacement = ids.map((id, index) => {
            const channel = byId.get(id);
            return channel ? { ...channel, number: numberSlots[index] } : null;
        });
        if (replacement.some(ch => ch === null)) { this.notice = { kind: 'error', text: 'The lineup changed. Start reorder again.' }; return false; }
        const outcome = await this.ports.manager.tryReplaceAllChannels(replacement as ChannelConfig[], { expectedBase: base });
        if (outcome.kind !== 'committed') {
            this.notice = { kind: 'error', text: outcome.kind === 'conflict' ? 'The lineup changed. Cancel reorder and start again.' : 'Order was not saved. Try again.' };
            return false;
        }
        this.cancelReorder();
        await this.afterCommit(outcome.pointerWarning, 'Order saved.');
        return true;
    }

    async deleteChannels(ids: readonly string[], capturedBase: ChannelStructuralBase, consentedMedia: ActiveMediaIdentity | null): Promise<DirectoryDeleteResult> {
        if (!this.canMutate || ids.length === 0 || !sameBase(capturedBase, this.ports.manager.getStructuralBase())) {
            this.notice = { kind: 'error', text: 'The lineup changed. Review the channels and confirm again.' }; return { kind: 'not-saved' };
        }
        const original = this.channels, deleted = new Set(ids);
        if (deleted.size !== ids.length || original.filter(ch => deleted.has(ch.id)).length !== deleted.size) {
            this.notice = { kind: 'error', text: 'The selection changed. Review it and confirm again.' }; return { kind: 'not-saved' };
        }
        const oldFocusIndex = original.findIndex(ch => ch.id === this.focusedChannelId);
        const media = this.ports.getActiveMediaIdentity();
        const active: ActiveMediaIdentity | null = media?.scopeKey === this.ports.getDirectoryScopeKey() ? media : null;
        if (!sameActiveMedia(active, consentedMedia)) {
            this.notice = { kind: 'error', text: 'Playback changed. Review the deletion warning and confirm again.' };
            return { kind: 'not-saved' };
        }
        const outcome = await this.ports.manager.tryReplaceAllChannels(original.filter(ch => !deleted.has(ch.id)), { expectedBase: capturedBase });
        if (outcome.kind !== 'committed') {
            this.notice = { kind: 'error', text: outcome.kind === 'conflict' ? 'The lineup changed. Review and confirm again.' : 'Channels were not deleted. Try again.' };
            return { kind: 'not-saved' };
        }
        const survivors = this.channels;
        this.selectedIds.clear(); this.mode = 'browse';
        this.focusedChannelId = survivors[Math.min(Math.max(oldFocusIndex, 0), survivors.length - 1)]?.id ?? null;
        this.repairFocus();
        let effectWarning = '';
        let mediaStopped = false;
        if (active && deleted.has(active.channelId)) {
            try {
                const effect = await this.ports.stopDeletedMediaIfCurrent(active);
                mediaStopped = effect === 'stopped';
            } catch { effectWarning = 'Playback could not be stopped automatically. Return to Guide or retry playback recovery.'; }
        }
        await this.afterCommit(outcome.pointerWarning, `${ids.length} channel${ids.length === 1 ? '' : 's'} deleted.`, effectWarning);
        return { kind: 'saved', openGuide: mediaStopped && survivors.length > 0 };
    }

    private async afterCommit(pointerWarning: boolean, savedText: string, effectWarning = ''): Promise<void> {
        let refreshWarning = '';
        try { await this.ports.refreshAfterCommit(); }
        catch { refreshWarning = 'Guide refresh failed. Reopen Guide to refresh it.'; }
        const warnings = [pointerWarning ? 'Current-channel pointer could not be saved; check it after restart.' : '', effectWarning, refreshWarning].filter(Boolean);
        this.notice = warnings.length
            ? { kind: 'saved-warning', text: `${savedText} ${warnings.join(' ')}` }
            : { kind: 'saved', text: savedText };
    }

    async checkHealth(id: string): Promise<void> {
        this.refreshHealthBase();
        if (!this.canMutate || this.healthControllers.has(id) || this.healthControllers.size >= 2 || !this.channels.some(ch => ch.id === id)) return;
        const controller = new AbortController(), epoch = this.epoch;
        this.healthControllers.set(id, controller);
        this.health.set(id, { kind: 'loading' });
        try {
            const resolved = await this.ports.manager.resolveChannelContent(id, { signal: controller.signal, cacheMode: 'revalidate' });
            if (controller.signal.aborted || epoch !== this.epoch || !this.channels.some(ch => ch.id === id)) return;
            this.health.set(id, resolved.isStale
                ? { kind: 'stale', checkedAt: this.ports.now(), detail: 'Cached content; source needs a retry.' }
                : resolved.orderedItems.length === 0
                    ? { kind: 'offair', checkedAt: this.ports.now(), detail: 'No playable programs found.' }
                    : { kind: 'healthy', checkedAt: this.ports.now(), detail: `${resolved.orderedItems.length} programs ready.` });
        } catch {
            if (!controller.signal.aborted && epoch === this.epoch) this.health.set(id, { kind: 'failed', checkedAt: this.ports.now(), detail: 'Source could not be checked. Retry.' });
        } finally {
            if (this.healthControllers.get(id) === controller) this.healthControllers.delete(id);
        }
    }
    cancelHealth(): void {
        this.epoch++;
        for (const [id, controller] of this.healthControllers) {
            controller.abort();
            if (this.health.get(id)?.kind === 'loading') this.health.set(id, { kind: 'unchecked' });
        }
        this.healthControllers.clear();
    }
    private refreshHealthBase(): void {
        const base = this.ports.manager.getStructuralBase();
        if (sameBase(base, this.healthBase)) return;
        this.cancelHealth(); this.health.clear(); this.healthBase = base;
    }
    close(): void {
        this.cancelHealth(); this.health.clear(); this.healthBase = this.ports.manager.getStructuralBase();
        this.cancelReorder(); this.cancelSelection(); this.query = ''; this.filter = 'all';
    }
}
