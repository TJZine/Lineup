import type { ChannelConfig } from '../../../scheduler/channel-manager/contracts/types';
import type { ChannelDirectoryPorts } from '../ChannelDirectoryPorts';
import type { ChannelMutationOutcome, ChannelStructuralBase } from '../../../scheduler/channel-manager/contracts/ChannelDurability';
import { ChannelDirectoryModel, projectDirectoryRows, sourceLabel } from '../ChannelDirectoryModel';

function channel(id: string, number: number, name = id): ChannelConfig {
    return {
        id, number, name, contentSource: { type: 'manual', items: [] }, playbackMode: 'sequential',
        startTimeAnchor: 0, skipIntros: false, skipCredits: false, createdAt: 0, updatedAt: 0,
        lastContentRefresh: 0, itemCount: 0, totalDurationMs: 0,
    };
}

// The fixture returns typed spies and mutable test controls together.
// eslint-disable-next-line @typescript-eslint/explicit-function-return-type
function fixture(initial = [channel('a', 10), channel('b', 30), channel('c', 80)]) {
    let channels = initial;
    let revision = 1;
    let loadKind: ReturnType<ChannelDirectoryPorts['manager']['getLastLoadOutcome']>['kind'] = 'readable';
    let active: ReturnType<ChannelDirectoryPorts['getActiveMediaIdentity']> = null;
    const replace = jest.fn<Promise<ChannelMutationOutcome<void>>, [ChannelConfig[], { expectedBase?: ChannelStructuralBase }?]>(async (next, options) => {
        if (options?.expectedBase?.revision !== revision) return { kind: 'conflict' as const, error: new Error('stale') };
        channels = next; revision++;
        return { kind: 'committed' as const, value: undefined, revision, pointerWarning: false };
    });
    const stop = jest.fn<Promise<'stopped' | 'superseded'>, []>(async () => 'stopped');
    const refresh = jest.fn(async () => undefined);
    const ports: ChannelDirectoryPorts = {
        manager: {
            getLastLoadOutcome: () => ({ kind: loadKind, generation: 1, revision, channelCount: channels.length }) as ReturnType<ChannelDirectoryPorts['manager']['getLastLoadOutcome']>,
            getStructuralBase: () => ({ generation: 1, revision }),
            getAllChannels: () => channels,
            tryReplaceAllChannels: replace,
            resolveChannelContent: jest.fn(async id => ({
                channelId: id, channelSnapshot: channels[0] ?? channel(id, 1), resolvedAt: 100,
                items: [], orderedItems: [], totalDurationMs: 0,
            })),
        },
        navigation: {
            registerFocusable: jest.fn(), unregisterFocusable: jest.fn(), setFocus: jest.fn(),
            getFocusedElement: jest.fn(() => null), on: jest.fn(() => ({ dispose: jest.fn() })), off: jest.fn(),
            openModal: jest.fn(), closeModal: jest.fn(), isModalOpen: jest.fn(() => false),
        },
        openStudio: jest.fn(), openGenerate: jest.fn(), goBack: jest.fn(),
        getActiveMediaIdentity: () => active,
        getDirectoryScopeKey: () => 'profile:server',
        stopDeletedMediaIfCurrent: stop, refreshAfterCommit: refresh, openGuideAfterActiveDelete: jest.fn(),
        now: () => 123,
    };
    return { ports, replace, stop, refresh, setLoad: (kind: typeof loadKind): void => { loadKind = kind; },
        setActive: (value: typeof active): void => { active = value; }, setRevision: (value: number): void => { revision = value; },
        getChannels: (): ChannelConfig[] => channels };
}

describe('ChannelDirectoryModel', () => {
    test('projects all source kinds and playback modes, searching name and number', () => {
        const sources: ChannelConfig['contentSource'][] = [
            { type: 'library', libraryId: 'l', libraryType: 'show', includeWatched: true },
            { type: 'collection', collectionKey: 'c', collectionName: 'Classic' },
            { type: 'show', showKey: 's', showName: 'Orbit' },
            { type: 'playlist', playlistKey: 'p', playlistName: 'Tonight' },
            { type: 'manual', items: [{ ratingKey: '1', title: 'One', durationMs: 10 }] },
            { type: 'mixed', sources: [{ type: 'manual', items: [] }], mixMode: 'sequential' },
        ];
        expect(sources.map(sourceLabel)).toEqual(['TV library', 'Collection · Classic', 'Show · Orbit', 'Playlist · Tonight', '1 hand-picked program', '1 mixed source']);
        const all = sources.map((source, i) => ({ ...channel(String(i), (i + 1) * 10, `Name ${i}`), contentSource: source,
            playbackMode: (['sequential', 'shuffle', 'block', 'random'] as const)[i % 4] ?? 'sequential', isAutoGenerated: i % 2 === 0 }));
        expect(projectDirectoryRows(all, 'all', '30', new Map()).map(row => row.channel.id)).toEqual(['2']);
        expect(projectDirectoryRows(all, 'generated', 'name', new Map()).map(row => row.channel.id)).toEqual(['0', '2', '4']);
        expect(projectDirectoryRows(all, 'custom', '', new Map()).map(row => row.channel.id)).toEqual(['1', '3', '5']);
        expect(projectDirectoryRows(all, 'all', '', new Map()).map(row => row.playback).slice(0, 4)).toEqual(['In order', 'Mix it up', 'Mini marathon', 'Random']);
    });

    test('selection is full identity roster even when filter hides selected rows; Back-like cancel is local', () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        model.beginSelection(); model.toggleSelected('a'); model.setQuery('b'); model.selectAllMatching();
        expect(model.allSelectedChannels.map(ch => ch.id)).toEqual(['a', 'b']);
        model.cancelSelection(); expect(model.mode).toBe('browse'); expect(model.selectedIds.size).toBe(0);
    });

    test('reorder preserves sorted number slots and drafts cancel without persistence', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        model.setQuery('a'); expect(model.beginReorder()).toBe(false); expect(f.replace).not.toHaveBeenCalled();
        model.setQuery(''); expect(model.beginReorder()).toBe(true);
        expect(model.move('b', -1)).toBe(true); expect(model.proposedNumber('b')).toBe(10);
        model.cancelReorder(); expect(f.replace).not.toHaveBeenCalled();
        model.beginReorder(); model.move('b', -1); expect(await model.saveOrder()).toBe(true);
        expect(f.getChannels().map(ch => [ch.id, ch.number])).toEqual([['b', 10], ['a', 30], ['c', 80]]);
        expect(f.replace).toHaveBeenCalledTimes(1);
    });

    test('selection cannot leak through reorder cancellation or save', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        model.beginSelection(); model.toggleSelected('a'); model.beginReorder();
        expect(model.selectedIds.size).toBe(0);
        model.move('b', -1); model.cancelReorder(); expect(model.selectedIds.size).toBe(0);
        model.beginSelection(); model.toggleSelected('a'); model.beginReorder(); model.move('b', -1);
        expect(await model.saveOrder()).toBe(true); expect(model.mode).toBe('browse');
        expect(model.selectedIds.size).toBe(0);
    });

    test('stale reorder and storage failure retain draft and old rows', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        model.beginReorder(); model.move('b', -1); f.setRevision(2);
        expect(await model.saveOrder()).toBe(false); expect(f.replace).not.toHaveBeenCalled();
        model.cancelReorder(); f.setRevision(1); model.beginReorder(); model.move('b', -1);
        f.replace.mockResolvedValueOnce({ kind: 'storage-failure', error: new Error('quota') });
        expect(await model.saveOrder()).toBe(false); expect(model.mode).toBe('reorder');
        expect(f.getChannels().map(ch => ch.id)).toEqual(['a', 'b', 'c']);
    });

    test('bulk deletion commits once, then stops only captured active media and retains saved warnings', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        f.setActive({ sessionId: 'session-1', scopeKey: 'profile:server', channelId: 'b' });
        model.setFocusedChannel('b'); const base = f.ports.manager.getStructuralBase();
        f.refresh.mockRejectedValueOnce(new Error('guide'));
        expect(await model.deleteChannels(['a', 'b'], base, f.ports.getActiveMediaIdentity())).toEqual({ kind: 'saved', openGuide: true });
        expect(f.replace).toHaveBeenCalledTimes(1);
        expect(f.stop).toHaveBeenCalledWith({ sessionId: 'session-1', scopeKey: 'profile:server', channelId: 'b' });
        expect(model.focusedChannelId).toBe('c');
        expect(model.notice?.kind).toBe('saved-warning');
    });

    test('failed delete never stops media or changes roster; superseded media is not routed to Guide', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        f.setActive({ sessionId: 'old', scopeKey: 'profile:server', channelId: 'a' });
        f.replace.mockResolvedValueOnce({ kind: 'storage-failure', error: new Error('quota') });
        const base = f.ports.manager.getStructuralBase();
        expect(await model.deleteChannels(['a', 'b'], base, f.ports.getActiveMediaIdentity())).toEqual({ kind: 'not-saved' });
        expect(f.stop).not.toHaveBeenCalled(); expect(f.getChannels()).toHaveLength(3);
        f.stop.mockResolvedValueOnce('superseded');
        expect(await model.deleteChannels(['a'], base, f.ports.getActiveMediaIdentity())).toEqual({ kind: 'saved', openGuide: false });
        expect(f.ports.openGuideAfterActiveDelete).not.toHaveBeenCalled();
    });

    test('unreadable load cannot be mistaken for empty or authorize mutation', async () => {
        const f = fixture([]); const model = new ChannelDirectoryModel(f.ports);
        f.setLoad('unreadable'); expect(model.canMutate).toBe(false);
        expect(await model.deleteChannels(['x'], f.ports.manager.getStructuralBase(), null)).toEqual({ kind: 'not-saved' });
        expect(f.replace).not.toHaveBeenCalled();
    });

    test('matching ID in another media scope is never stopped', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        f.setActive({ sessionId: 'other', scopeKey: 'another-profile', channelId: 'a' });
        expect(await model.deleteChannels(['a'], f.ports.manager.getStructuralBase(), null)).toEqual({ kind: 'saved', openGuide: false });
        expect(f.stop).not.toHaveBeenCalled();
    });

    test('media identity changed after consent prevents the body write', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        const consent = { sessionId: 'old', scopeKey: 'profile:server', channelId: 'a' };
        f.setActive({ sessionId: 'new', scopeKey: 'profile:server', channelId: 'a' });
        expect(await model.deleteChannels(['a'], f.ports.manager.getStructuralBase(), consent)).toEqual({ kind: 'not-saved' });
        expect(f.replace).not.toHaveBeenCalled(); expect(f.stop).not.toHaveBeenCalled();
    });

    test('deleting the final tuned channel stops media and leaves the empty directory open', async () => {
        const f = fixture([channel('a', 10)]); const model = new ChannelDirectoryModel(f.ports);
        f.setActive({ sessionId: 'last', scopeKey: 'profile:server', channelId: 'a' });
        expect(await model.deleteChannels(['a'], f.ports.manager.getStructuralBase(), f.ports.getActiveMediaIdentity())).toEqual({ kind: 'saved', openGuide: false });
        expect(f.stop).toHaveBeenCalledTimes(1);
        expect(f.ports.openGuideAfterActiveDelete).not.toHaveBeenCalled();
        expect(model.channels).toHaveLength(0);
    });

    test('explicit health is bounded, canceled on close, and reports off air or failure', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        let resolveFirst: ((value: Awaited<ReturnType<ChannelDirectoryPorts['manager']['resolveChannelContent']>>) => void) | undefined;
        const pending = new Promise<Awaited<ReturnType<ChannelDirectoryPorts['manager']['resolveChannelContent']>>>(resolve => { resolveFirst = resolve; });
        const resolve = f.ports.manager.resolveChannelContent as jest.Mock;
        resolve.mockReturnValueOnce(pending);
        const first = model.checkHealth('a'); const second = model.checkHealth('b');
        await model.checkHealth('c'); expect(resolve).toHaveBeenCalledTimes(2);
        model.close(); resolveFirst?.({ channelId: 'a', channelSnapshot: channel('a', 10), resolvedAt: 100, items: [], orderedItems: [], totalDurationMs: 0 });
        await Promise.all([first, second]); expect(model.health.get('a')).toBeUndefined();
        resolve.mockRejectedValueOnce(new Error('offline'));
        await model.checkHealth('c'); expect(model.health.get('c')?.kind).toBe('failed');
        await model.checkHealth('b'); expect(model.health.get('b')?.kind).toBe('offair');
    });

    test('a changed structural base invalidates old health for the same channel ID', async () => {
        const f = fixture(); const model = new ChannelDirectoryModel(f.ports);
        await model.checkHealth('a'); expect(model.health.get('a')?.kind).toBe('offair');
        f.setRevision(2);
        expect(model.rows.find(row => row.channel.id === 'a')?.health).toEqual({ kind: 'unchecked' });
        expect(model.health.has('a')).toBe(false);
    });
});
