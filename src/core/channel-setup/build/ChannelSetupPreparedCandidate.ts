import type { ChannelConfig } from '../../../modules/scheduler/channel-manager';
import { MAX_CHANNEL_NUMBER } from '../../../modules/scheduler/channel-manager/constants';
import { ChannelAuthoringService } from '../../../modules/scheduler/channel-manager/authoring/ChannelAuthoringService';
import { createChannelIdentityKey, diffChannelPlans, type PendingChannel } from '../planning/ChannelSetupPlanningTypes';
import type { ChannelSetupConfig } from '../types';

export type ChannelSetupCandidateRow = {
    action: 'created' | 'retained' | 'changed' | 'removed';
    channelId: string;
    number: number;
    name: string;
    sourceLibraryId: string | null;
    sourceLibraryIds: readonly string[];
    sourceKind: ChannelConfig['contentSource']['type'];
    playbackMode: ChannelConfig['playbackMode'];
    shuffleSeed: number | null;
    startTimeAnchor: number;
    scheduleAnchorMode: 'daily' | 'fixed';
    blockSize: number | null;
    includeSpecials: boolean;
    buildStrategy: ChannelConfig['buildStrategy'] | null;
    reason: string;
};

export type ChannelSetupCandidate = {
    channels: ChannelConfig[];
    rows: ChannelSetupCandidateRow[];
    skipped: number;
    reachedMaxChannels: boolean;
};

function sourceLibraryId(channel: ChannelConfig): string | null {
    if (channel.sourceLibraryId) return channel.sourceLibraryId;
    if (channel.contentSource.type === 'library') return channel.contentSource.libraryId;
    return null;
}

function relevantLibraryIds(channel: ChannelConfig): Set<string> {
    const ids = new Set<string>();
    if (channel.sourceLibraryId) ids.add(channel.sourceLibraryId);
    const visit = (source: ChannelConfig['contentSource']): void => {
        if (source.type === 'library') ids.add(source.libraryId);
        if (source.type === 'mixed') source.sources.forEach(visit);
    };
    visit(channel.contentSource);
    return ids;
}

function makeRow(channel: ChannelConfig, action: ChannelSetupCandidateRow['action'], reason: string): ChannelSetupCandidateRow {
    return { action, channelId: channel.id, number: channel.number, name: channel.name,
        sourceLibraryId: sourceLibraryId(channel), sourceLibraryIds: Array.from(relevantLibraryIds(channel)),
        sourceKind: channel.contentSource.type,
        playbackMode: channel.playbackMode, shuffleSeed: channel.shuffleSeed ?? null,
        startTimeAnchor: channel.startTimeAnchor, blockSize: channel.blockSize ?? null,
        scheduleAnchorMode: channel.scheduleAnchorMode === 'fixed' ? 'fixed' : 'daily',
        includeSpecials: channel.includeSpecials !== false,
        buildStrategy: channel.buildStrategy ?? null, reason };
}

const PLANNED_OPTIONAL_FIELDS = [
    'contentFilters', 'sortOrder', 'blockSize', 'buildStrategy', 'sourceLibraryId',
    'sourceLibraryName', 'lineupReplicaIndex', 'isPlaybackModeVariant', 'includeSpecials',
] as const;

function mergeMatchedChannel(existing: ChannelConfig, planned: PendingChannel, now: number): {
    channel: ChannelConfig;
    changed: boolean;
} {
    const updated: ChannelConfig = {
        ...existing,
        contentSource: planned.contentSource,
        playbackMode: planned.playbackMode,
        shuffleSeed: planned.shuffleSeed,
        startTimeAnchor: planned.startTimeAnchor ?? existing.startTimeAnchor,
        name: existing.isAutoGenerated ? planned.name : existing.name,
    };
    if (planned.scheduleAnchorMode === 'fixed') updated.scheduleAnchorMode = 'fixed';
    else delete updated.scheduleAnchorMode;
    for (const field of PLANNED_OPTIONAL_FIELDS) {
        const value = planned[field];
        if (value === undefined) delete updated[field];
        else Object.assign(updated, { [field]: value });
    }
    const authored = (channel: ChannelConfig): unknown => ({
        name: channel.name,
        contentSource: channel.contentSource,
        playbackMode: channel.playbackMode,
        shuffleSeed: channel.shuffleSeed,
        startTimeAnchor: channel.scheduleAnchorMode === 'fixed' ? channel.startTimeAnchor : null,
        scheduleAnchorMode: channel.scheduleAnchorMode === 'fixed' ? 'fixed' : 'daily',
        optional: PLANNED_OPTIONAL_FIELDS.map((field) => channel[field] ?? null),
    });
    const changed = JSON.stringify(authored(existing)) !== JSON.stringify(authored(updated));
    if (!changed) return { channel: existing, changed: false };
    updated.updatedAt = now;
    updated.lastContentRefresh = 0;
    updated.itemCount = 0;
    updated.totalDurationMs = 0;
    return { channel: updated, changed: true };
}

/** Pure structural allocation. Runtime content resolution is never needed to obtain consent. */
export function buildChannelSetupCandidate(
    config: ChannelSetupConfig,
    existing: readonly ChannelConfig[],
    pending: readonly PendingChannel[],
    unknownLibraryIds: readonly string[],
    confirmedDeselectedLibraryIds: readonly string[] = [],
    now: () => number = Date.now,
    generateId: () => string = () => `setup-${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`,
    sharedPlaylistComplete = false
): ChannelSetupCandidate {
    const authoring = new ChannelAuthoringService({ now, generateId });
    // Generated plan identities must never consume or rewrite an authored channel.
    const diff = diffChannelPlans(existing.filter((channel) => channel.isAutoGenerated), [...pending]);
    const unknown = new Set(unknownLibraryIds);
    const selected = new Set(config.selectedLibraryIds);
    const confirmedDeselected = new Set(confirmedDeselectedLibraryIds);
    const matched = new Map(diff.matchedPairs.map((pair) => [pair.existing.id, pair.planned]));
    const preserved = config.buildMode === 'replace'
        ? existing.filter((channel) => {
            if (!channel.isAutoGenerated || matched.has(channel.id)) return true;
            if (channel.contentSource.type === 'playlist') return !sharedPlaylistComplete;
            const ids = relevantLibraryIds(channel);
            return ids.size === 0 || Array.from(ids).some((id) => unknown.has(id)
                || (!selected.has(id) && !confirmedDeselected.has(id)));
        })
        : [...existing];
    const rows: ChannelSetupCandidateRow[] = [];
    let channels: ChannelConfig[] = [];
    for (const channel of preserved) {
        const planned = matched.get(channel.id);
        if (config.buildMode !== 'append' && planned) {
            const merged = mergeMatchedChannel(channel, planned, now());
            channels.push(merged.channel);
            rows.push(makeRow(merged.channel, merged.changed ? 'changed' : 'retained', 'Matched generated source'));
        } else {
            channels.push(channel);
            rows.push(makeRow(channel, 'retained', Array.from(relevantLibraryIds(channel)).some((id) => unknown.has(id))
                || channel.contentSource.type === 'playlist' && !sharedPlaylistComplete
                ? 'Inventory unavailable; preserved' : 'Existing channel retained'));
        }
    }
    const retainedIds = new Set(channels.map((channel) => channel.id));
    for (const channel of existing) {
        if (!retainedIds.has(channel.id)) rows.push(makeRow(channel, 'removed', 'Complete selected library replaced'));
    }
    const consumed = new Map<string, number>();
    for (const pair of diff.matchedPairs) {
        const key = createChannelIdentityKey(pair.planned);
        consumed.set(key, (consumed.get(key) ?? 0) + 1);
    }
    let skipped = 0;
    let reachedMaxChannels = false;
    for (const item of pending) {
        const key = createChannelIdentityKey(item);
        const count = consumed.get(key) ?? 0;
        if (count > 0) {
            consumed.set(key, count - 1);
            continue;
        }
        if (channels.length >= MAX_CHANNEL_NUMBER) {
            skipped++;
            reachedMaxChannels = true;
            continue;
        }
        const number = authoring.getNextAvailableNumber(channels);
        const created = authoring.createChannel({ ...item, number }, channels);
        channels.push(created);
        rows.push(makeRow(created, 'created', 'Selected generated source'));
    }
    channels = channels.sort((a, b) => a.number - b.number);
    authoring.buildReplacementState(channels);
    return { channels, rows, skipped, reachedMaxChannels };
}
