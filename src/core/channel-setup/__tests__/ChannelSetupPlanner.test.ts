import { buildChannelSetupPlan, createChannelIdentityKey, diffChannelPlans } from '../ChannelSetupPlanner';
import type { ChannelSetupConfig, SetupStrategyConfig, SetupStrategyKey } from '../types';
import type { PlexLibraryType, PlexPlaylist } from '../../../modules/plex/library';
import type { ChannelConfig } from '../../../modules/scheduler/channel-manager';
import type { PendingChannel } from '../ChannelSetupPlanner';
import { DEFAULT_STRATEGY_PRIORITIES, MIXED_SCOPE_STRATEGY_KEYS, SETUP_STRATEGY_KEYS } from '../constants';

const seedFor = (value: string): number => {
    let hash = 0;
    for (let i = 0; i < value.length; i++) {
        hash = ((hash << 5) - hash) + value.charCodeAt(i);
        hash |= 0;
    }
    return Math.abs(hash);
};

const createStrategyConfig = (
    overrides?: Partial<Record<SetupStrategyKey, Partial<SetupStrategyConfig>>>
): Record<SetupStrategyKey, SetupStrategyConfig> => (
    SETUP_STRATEGY_KEYS.reduce<Record<SetupStrategyKey, SetupStrategyConfig>>((acc, key) => {
        const candidate = overrides?.[key];
        acc[key] = {
            enabled: candidate?.enabled ?? false,
            priority: candidate?.priority ?? DEFAULT_STRATEGY_PRIORITIES[key],
            scope: MIXED_SCOPE_STRATEGY_KEYS.has(key) && candidate?.scope === 'cross-library' ? 'cross-library' : 'per-library',
        };
        return acc;
    }, {} as Record<SetupStrategyKey, SetupStrategyConfig>)
);

const createConfig = (overrides?: Partial<ChannelSetupConfig>): ChannelSetupConfig => ({
    serverId: 'server-1',
    selectedLibraryIds: [],
    maxChannels: 50,
    buildMode: 'replace',
    strategyConfig: createStrategyConfig(),
    actorStudioCombineMode: 'separate',
    minItemsPerChannel: 1,
    ...overrides,
});

const makeExistingChannel = (planned: PendingChannel, index: number): ChannelConfig => {
    const existing: ChannelConfig = {
        id: `ch-${index + 1}`,
        number: index + 1,
        name: `Existing ${index + 1}`,
        contentSource: planned.contentSource,
        playbackMode: planned.playbackMode,
        shuffleSeed: planned.shuffleSeed,
        phaseSeed: 1,
        startTimeAnchor: 0,
        skipIntros: false,
        skipCredits: false,
        createdAt: 0,
        updatedAt: 0,
        lastContentRefresh: 0,
        itemCount: 0,
        totalDurationMs: 0,
    };
    if (planned.isAutoGenerated !== undefined) {
        existing.isAutoGenerated = planned.isAutoGenerated;
    }
    if (planned.buildStrategy !== undefined) {
        existing.buildStrategy = planned.buildStrategy;
    }
    if (planned.sourceLibraryId !== undefined) {
        existing.sourceLibraryId = planned.sourceLibraryId;
    }
    if (planned.sourceLibraryName !== undefined) {
        existing.sourceLibraryName = planned.sourceLibraryName;
    }
    if (planned.lineupReplicaIndex !== undefined) {
        existing.lineupReplicaIndex = planned.lineupReplicaIndex;
    }
    if (planned.isSequentialVariant !== undefined) {
        existing.isSequentialVariant = planned.isSequentialVariant;
    }
    if (planned.blockSize !== undefined) {
        existing.blockSize = planned.blockSize;
    }
    return existing;
};

describe('ChannelSetupPlanner', () => {
    it('defaults alternateLineupCopies to 1 when addAlternateLineups is true but copies is non-finite', () => {
        const playlists: PlexPlaylist[] = [
            {
                ratingKey: 'pl1',
                key: '/playlists/pl1',
                title: 'Favorites',
                thumb: null,
                duration: 0,
                leafCount: 10,
            },
        ];

        const plan = buildChannelSetupPlan({
            config: createConfig({
                strategyConfig: createStrategyConfig({ playlists: { enabled: true } }),
                channelExpansion: {
                    addAlternateLineups: true,
                    alternateLineupCopies: Number.NaN,
                    variantType: 'none',
                    variantBlockSize: 3,
                },
            }),
            libraries: [],
            playlists,
            collectionsByLibraryId: new Map(),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        expect(plan.pendingChannels.map((c) => c.name)).toEqual(['Favorites', 'Favorites (2)']);
        expect(plan.pendingChannels.map((c) => c.lineupReplicaIndex)).toEqual([0, 1]);
    });

    it('diffChannelPlans matches base/copy/sequential variants without identity collisions', () => {
        const playlists: PlexPlaylist[] = [
            {
                ratingKey: 'pl1',
                key: '/playlists/pl1',
                title: 'Favorites',
                thumb: null,
                duration: 0,
                leafCount: 10,
            },
        ];

        const plan = buildChannelSetupPlan({
            config: createConfig({
                strategyConfig: createStrategyConfig({ playlists: { enabled: true } }),
                channelExpansion: {
                    addAlternateLineups: true,
                    alternateLineupCopies: 2,
                    variantType: 'sequential',
                    variantBlockSize: 3,
                },
            }),
            libraries: [],
            playlists,
            collectionsByLibraryId: new Map(),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        const identityKeys = plan.pendingChannels.map((channel) => createChannelIdentityKey(channel));
        expect(new Set(identityKeys).size).toBe(plan.pendingChannels.length);

        const existing: ChannelConfig[] = plan.pendingChannels.map(makeExistingChannel);

        const diff = diffChannelPlans(existing, plan.pendingChannels);
        expect(diff.summary).toEqual({ created: 0, removed: 0, unchanged: plan.pendingChannels.length });
        expect(diff.matchedPairs).toHaveLength(plan.pendingChannels.length);
    });

    it('generates block variants for series-derived channels with unique identity keys', () => {
        const plan = buildChannelSetupPlan({
            config: createConfig({
                selectedLibraryIds: ['s1'],
                strategyConfig: createStrategyConfig({ collections: { enabled: true } }),
                channelExpansion: {
                    addAlternateLineups: false,
                    alternateLineupCopies: 1,
                    variantType: 'block',
                    variantBlockSize: 4,
                },
            }),
            libraries: [{ id: 's1', title: 'Shows', type: 'show', contentCount: 10 }] as PlexLibraryType[],
            playlists: [],
            collectionsByLibraryId: new Map([
                ['s1', [{ ratingKey: 'co1', key: '/library/collections/co1', title: 'Classics', thumb: null, childCount: 10 }]],
            ]),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        const names = plan.pendingChannels.map((channel) => channel.name);
        expect(names).toContain('Classics');
        expect(names).toContain('Classics • Block');

        const blockVariant = plan.pendingChannels.find(
            (channel) => channel.name === 'Classics • Block'
        );
        expect(blockVariant).toBeDefined();
        expect(blockVariant?.playbackMode).toBe('block');
        expect(blockVariant?.blockSize).toBe(4);
        expect(blockVariant?.isSequentialVariant).toBe(true);

        const sequentialVariantCandidate: PendingChannel = {
            ...(blockVariant as PendingChannel),
            playbackMode: 'sequential',
        };
        expect(createChannelIdentityKey(blockVariant as PendingChannel)).not.toBe(
            createChannelIdentityKey(sequentialVariantCandidate)
        );
    });

    it('treats mixed TV-only channels as series-derived for base series ordering and variants', () => {
        const plan = buildChannelSetupPlan({
            config: createConfig({
                selectedLibraryIds: ['s1', 's2'],
                strategyConfig: createStrategyConfig({ actors: { enabled: true, scope: 'cross-library' } }),
                seriesOrdering: {
                    basePlaybackMode: 'block',
                    baseBlockSize: 3,
                },
                channelExpansion: {
                    addAlternateLineups: false,
                    alternateLineupCopies: 1,
                    variantType: 'sequential',
                    variantBlockSize: 3,
                },
            }),
            libraries: [
                { id: 's1', title: 'Shows A', type: 'show', contentCount: 10 },
                { id: 's2', title: 'Shows B', type: 'show', contentCount: 10 },
            ] as PlexLibraryType[],
            playlists: [],
            collectionsByLibraryId: new Map(),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map([
                ['s1', [{ key: 'actor-1', title: 'Jane Doe', count: 10 }]],
                ['s2', [{ key: 'actor-1', title: 'Jane Doe', count: 10 }]],
            ]),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        const base = plan.pendingChannels.find((channel) => channel.name === 'Jane Doe');
        expect(base).toBeDefined();
        expect(base?.contentSource.type).toBe('mixed');
        expect(base?.playbackMode).toBe('block');
        expect(base?.blockSize).toBe(3);

        const sequentialVariant = plan.pendingChannels.find((channel) => channel.name === 'Jane Doe • Sequential');
        expect(sequentialVariant).toBeDefined();
        expect(sequentialVariant?.playbackMode).toBe('sequential');
        expect(sequentialVariant?.isSequentialVariant).toBe(true);
    });

    it('sanitizes non-finite/invalid baseBlockSize for base series ordering', () => {
        const plan = buildChannelSetupPlan({
            config: createConfig({
                selectedLibraryIds: ['s1'],
                strategyConfig: createStrategyConfig({ collections: { enabled: true } }),
                seriesOrdering: {
                    basePlaybackMode: 'block',
                    baseBlockSize: Number.NaN,
                },
            }),
            libraries: [{ id: 's1', title: 'Shows', type: 'show', contentCount: 10 }] as PlexLibraryType[],
            playlists: [],
            collectionsByLibraryId: new Map([
                ['s1', [{ ratingKey: 'co1', key: '/library/collections/co1', title: 'Classics', thumb: null, childCount: 10 }]],
            ]),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        const base = plan.pendingChannels.find((channel) => channel.name === 'Classics');
        expect(base).toBeDefined();
        expect(base?.playbackMode).toBe('block');
        expect(base?.blockSize).toBe(3);
    });

    it('sanitizes non-finite/invalid variantBlockSize for block variants', () => {
        const plan = buildChannelSetupPlan({
            config: createConfig({
                selectedLibraryIds: ['s1'],
                strategyConfig: createStrategyConfig({ collections: { enabled: true } }),
                channelExpansion: {
                    addAlternateLineups: false,
                    alternateLineupCopies: 1,
                    variantType: 'block',
                    variantBlockSize: 0,
                },
            }),
            libraries: [{ id: 's1', title: 'Shows', type: 'show', contentCount: 10 }] as PlexLibraryType[],
            playlists: [],
            collectionsByLibraryId: new Map([
                ['s1', [{ ratingKey: 'co1', key: '/library/collections/co1', title: 'Classics', thumb: null, childCount: 10 }]],
            ]),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        const variant = plan.pendingChannels.find((channel) => channel.name === 'Classics • Block');
        expect(variant).toBeDefined();
        expect(variant?.playbackMode).toBe('block');
        expect(variant?.blockSize).toBe(3);
    });

    it('falls back when series ordering/variant types are runtime-invalid', () => {
        const plan = buildChannelSetupPlan({
            config: createConfig({
                selectedLibraryIds: ['s1'],
                strategyConfig: createStrategyConfig({ collections: { enabled: true } }),
                seriesOrdering: {
                    basePlaybackMode: 'bogus' as unknown as 'shuffle' | 'sequential' | 'block',
                    baseBlockSize: 3,
                },
                channelExpansion: {
                    addAlternateLineups: false,
                    alternateLineupCopies: 1,
                    variantType: 'bogus' as unknown as 'none' | 'sequential' | 'block',
                    variantBlockSize: 3,
                },
            }),
            libraries: [{ id: 's1', title: 'Shows', type: 'show', contentCount: 10 }] as PlexLibraryType[],
            playlists: [],
            collectionsByLibraryId: new Map([
                ['s1', [{ ratingKey: 'co1', key: '/library/collections/co1', title: 'Classics', thumb: null, childCount: 10 }]],
            ]),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map(),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        expect(plan.pendingChannels.map((channel) => channel.name)).toEqual(['Classics']);
        const base = plan.pendingChannels.find((channel) => channel.name === 'Classics');
        expect(base?.playbackMode).toBe('shuffle');
    });

    it('derives decades from summed year directories', () => {
        const plan = buildChannelSetupPlan({
            config: createConfig({
                selectedLibraryIds: ['s1'],
                strategyConfig: createStrategyConfig({ decades: { enabled: true } }),
                minItemsPerChannel: 5,
            }),
            libraries: [{ id: 's1', title: 'Shows', type: 'show', contentCount: 1200 }] as PlexLibraryType[],
            playlists: [],
            collectionsByLibraryId: new Map(),
            genresByLibraryId: new Map(),
            directorsByLibraryId: new Map(),
            yearsByLibraryId: new Map([
                ['s1', [
                    { key: '1981', title: '1981', count: 2 },
                    { key: '1988', title: '1988', count: 3 },
                    { key: '1995', title: '1995', count: 4 },
                ]],
            ]),
            actorsByLibraryId: new Map(),
            studiosByLibraryId: new Map(),
            warnings: [],
            seedFor,
        });

        expect(plan.pendingChannels.map((channel) => channel.name)).toContain('Shows - 1980s');
        expect(plan.pendingChannels.map((channel) => channel.name)).not.toContain('Shows - 1990s');
    });
});
