/** @jest-environment jsdom */

import { ChannelSetupBuildExecutor } from '../build/ChannelSetupBuildExecutor';
import { buildChannelSetupCandidate } from '../build/ChannelSetupPreparedCandidate';
import type { ChannelSetupPlanningService } from '../planning/ChannelSetupPlanningService';
import type { ChannelSetupBuildCommitter } from '../build/ChannelSetupBuildCommitter';
import type { ChannelConfig, IChannelManager } from '../../../modules/scheduler/channel-manager';
import type { ChannelSetupConfig } from '../types';

const config = (): ChannelSetupConfig => ({
    serverId: 's1', selectedLibraryIds: ['ready', 'failed'], maxChannels: 500, buildMode: 'replace',
    strategyConfig: {
        collections: { enabled: false, priority: 1, scope: 'per-library' },
        playlists: { enabled: false, priority: 2, scope: 'per-library' },
        genres: { enabled: false, priority: 3, scope: 'per-library' },
        directors: { enabled: false, priority: 4, scope: 'per-library' },
        decades: { enabled: false, priority: 5, scope: 'per-library' },
        recentlyAdded: { enabled: true, priority: 6, scope: 'per-library' },
        studios: { enabled: false, priority: 7, scope: 'per-library' },
        actors: { enabled: false, priority: 8, scope: 'per-library' },
    }, actorStudioCombineMode: 'separate', minItemsPerChannel: 1,
});

const source = (libraryId: string): ChannelConfig['contentSource'] =>
    ({ type: 'library', libraryId, libraryType: 'movie', includeWatched: true });

const existing = (id: string, libraryId: string, number: number): ChannelConfig => ({
    id, number, name: id, contentSource: source(libraryId), playbackMode: 'shuffle',
    shuffleSeed: 3, phaseSeed: 3, startTimeAnchor: 123, skipIntros: false, skipCredits: false,
    createdAt: 100, updatedAt: 100, lastContentRefresh: 0, itemCount: 0, totalDurationMs: 0,
    sourceLibraryId: libraryId, isAutoGenerated: true,
});

const inventory = {
    scopeKey: JSON.stringify(['u1', 's1']), generation: 4,
    sharedPlaylistsStatus: 'unused' as const,
    libraries: [
        { libraryId: 'ready', libraryName: 'Ready', requiredFamilies: ['recentlyAdded'] as const,
            status: 'ready' as const, generation: 4 },
        { libraryId: 'failed', libraryName: 'Failed', requiredFamilies: ['recentlyAdded'] as const,
            status: 'failed' as const, generation: 4, reason: 'Plex unavailable' },
    ],
    acceptedReadyLibraryIds: ['ready'],
};

const pending = {
    name: 'New', contentSource: source('ready'), playbackMode: 'shuffle' as const,
    shuffleSeed: 8, sourceLibraryId: 'ready', isAutoGenerated: true,
};

describe('prepared setup candidate', () => {
    it('allocates exact IDs/numbers before consent and retains unknown-library channels', () => {
        const old = [existing('unknown-id', 'failed', 17)];
        const candidate = buildChannelSetupCandidate(config(), old, [pending], ['failed'], [], () => 456, () => 'new-id');
        expect(candidate.channels.map((channel) => [channel.id, channel.number])).toEqual([
            ['new-id', 1], ['unknown-id', 17],
        ]);
        expect(candidate.rows.map((row) => [row.action, row.channelId])).toEqual([
            ['retained', 'unknown-id'], ['created', 'new-id'],
        ]);
        expect(candidate.channels[0]).toMatchObject({ shuffleSeed: 8, startTimeAnchor: 456 });
    });

    it('keeps matched generated identity in replace and uses free numbers in append', () => {
        const old = [existing('matched-id', 'ready', 8), existing('other-id', 'failed', 17)];
        const matching = { ...pending, name: 'matched-id', shuffleSeed: 3 };
        const replacement = buildChannelSetupCandidate(config(), old, [matching], ['failed'], [],
            () => 456, () => 'unused');
        expect(replacement.channels.map((item) => [item.id, item.number, item.startTimeAnchor])).toEqual([
            ['matched-id', 8, 123], ['other-id', 17, 123],
        ]);
        expect(replacement.rows.every((row) => row.action === 'retained')).toBe(true);

        const appended = buildChannelSetupCandidate({ ...config(), buildMode: 'append' }, old,
            [{ ...pending, contentSource: source('new'), sourceLibraryId: 'new' }],
            ['failed'], [], () => 456, () => 'new-id');
        expect(appended.channels.map((item) => [item.id, item.number])).toEqual([
            ['new-id', 1], ['matched-id', 8], ['other-id', 17],
        ]);

        const merged = buildChannelSetupCandidate({ ...config(), buildMode: 'merge' }, old,
            [{ ...matching, playbackMode: 'sequential' }], ['failed'], [], () => 456, () => 'unused');
        expect(merged.channels.find((item) => item.id === 'matched-id')).toMatchObject({
            number: 8, playbackMode: 'sequential', startTimeAnchor: 123,
        });
        expect(merged.rows.find((row) => row.channelId === 'matched-id')?.action).toBe('changed');
    });

    it('reviews and retains explicit anchor and block-specials changes on a matched channel', () => {
        const old = [{ ...existing('matched-id', 'ready', 8), playbackMode: 'block' as const,
            blockSize: 3, includeSpecials: true }];
        const planned = { ...pending, playbackMode: 'block' as const, blockSize: 3,
            includeSpecials: false, startTimeAnchor: 999, scheduleAnchorMode: 'fixed' as const, shuffleSeed: 44 };
        const candidate = buildChannelSetupCandidate(config(), old, [planned], [], [],
            () => 456, () => 'unused');
        expect(candidate.rows.find((row) => row.channelId === 'matched-id')).toMatchObject({
            action: 'changed', startTimeAnchor: 999, scheduleAnchorMode: 'fixed', includeSpecials: false, shuffleSeed: 44,
        });
        expect(candidate.channels[0]).toMatchObject({
            id: 'matched-id', startTimeAnchor: 999, scheduleAnchorMode: 'fixed', includeSpecials: false, shuffleSeed: 44,
        });
    });

    it('clears a matched fixed anchor for Automatic without rewriting its historical timestamp', () => {
        const old = [{ ...existing('matched-id', 'ready', 8), scheduleAnchorMode: 'fixed' as const }];
        const planned = { ...pending, name: 'matched-id', shuffleSeed: 3 };
        const candidate = buildChannelSetupCandidate(config(), old, [planned], [], [],
            () => 456, () => 'unused');
        expect(candidate.rows[0]).toMatchObject({ action: 'changed', scheduleAnchorMode: 'daily', startTimeAnchor: 123 });
        expect(candidate.channels[0]).toMatchObject({ id: 'matched-id', startTimeAnchor: 123 });
        expect(candidate.channels[0]).not.toHaveProperty('scheduleAnchorMode');
        expect(candidate.channels[0]?.updatedAt).toBe(456);
    });

    it('preserves authored channels even when a generated plan uses the same source', () => {
        const manual = { ...existing('manual-id', 'ready', 8), isAutoGenerated: false };
        const candidate = buildChannelSetupCandidate(config(), [manual], [pending], [], [],
            () => 456, () => 'generated-id');

        expect(candidate.channels.map((channel) => channel.id)).toEqual(['generated-id', 'manual-id']);
        expect(candidate.rows.map((row) => [row.action, row.channelId])).toEqual([
            ['retained', 'manual-id'], ['created', 'generated-id'],
        ]);
    });

    it('requires known inventory to remove a deselected library and enforces the 500-number ceiling', () => {
        const old = [existing('deselected', 'other', 7)];
        const preserved = buildChannelSetupCandidate(config(), old, [pending], [], [],
            () => 456, () => 'new-id');
        expect(preserved.rows.find((row) => row.channelId === 'deselected')?.action).toBe('retained');
        const removed = buildChannelSetupCandidate(config(), old, [pending], [], ['other'],
            () => 456, () => 'new-id');
        expect(removed.rows.find((row) => row.channelId === 'deselected')?.action).toBe('removed');

        const full = Array.from({ length: 500 }, (_, index) => existing(`id-${index}`, 'failed', index + 1));
        const capped = buildChannelSetupCandidate({ ...config(), buildMode: 'append' }, full,
            [pending], ['failed']);
        expect(capped.channels).toHaveLength(500);
        expect(capped.skipped).toBe(1);
        expect(capped.reachedMaxChannels).toBe(true);
    });

    it('removes obsolete shared playlists only with complete shared facts', () => {
        const playlist: ChannelConfig = { ...existing('playlist-id', 'ready', 8),
            buildStrategy: 'playlists' as const,
            contentSource: { type: 'playlist' as const, playlistKey: 'playlist-1', playlistName: 'Old' } };
        delete playlist.sourceLibraryId;
        const unknown = buildChannelSetupCandidate(config(), [playlist], [pending], [], [],
            () => 456, () => 'new-id', false);
        expect(unknown.rows.find((row) => row.channelId === 'playlist-id')?.action).toBe('retained');
        const complete = buildChannelSetupCandidate(config(), [playlist], [pending], [], [],
            () => 456, () => 'new-id', true);
        expect(complete.rows.find((row) => row.channelId === 'playlist-id')?.action).toBe('removed');
    });

    it('removes an obsolete cross-library source only after all affected libraries are known or confirmed', () => {
        const cross: ChannelConfig = { ...existing('cross-id', 'ready', 8),
            contentSource: { type: 'mixed' as const, mixMode: 'interleave' as const,
                sources: [source('ready'), source('other')] } };
        delete cross.sourceLibraryId;
        const incomplete = buildChannelSetupCandidate(config(), [cross], [pending], ['other'], [],
            () => 456, () => 'new-id');
        expect(incomplete.rows.find((row) => row.channelId === 'cross-id')?.action).toBe('retained');
        const complete = buildChannelSetupCandidate(config(), [cross], [pending], [], ['other'],
            () => 456, () => 'new-id');
        expect(complete.rows.find((row) => row.channelId === 'cross-id')?.action).toBe('removed');
    });

    it('holds a prepared candidate across Apply, rejects stale base and requires separate protected consent', async () => {
        let base = { generation: 2, revision: 3 };
        let inventoryGeneration = 4;
        let scopeKey = inventory.scopeKey;
        const manager = {
            getStructuralBase: jest.fn(() => base),
            getLastLoadOutcome: jest.fn(() => ({ kind: 'unreadable', generation: 2, revision: 3, replacementHandle: 'initial' })),
            prepareProtectedReplacement: jest.fn(() => ({ kind: 'unreadable', generation: 2, revision: 3, replacementHandle: 'fresh' })),
            cancelProtectedReplacement: jest.fn(),
            getAllChannels: jest.fn(() => []),
        } as unknown as jest.Mocked<IChannelManager>;
        const planning = {
            scanSetupInventory: jest.fn().mockResolvedValue(inventory),
            buildAcceptedPlan: jest.fn().mockResolvedValue({
                plan: { pendingChannels: [pending], estimates: { total: 1 },
                    warnings: [], skipped: 0, reachedMaxChannels: false },
                warnings: ['Playlist count recovered'], canceled: false,
            }),
            get inventoryGeneration() { return inventoryGeneration; },
            getCurrentScopeKey: jest.fn(() => scopeKey),
            isLibraryInventoryReady: jest.fn(() => true),
        } as unknown as jest.Mocked<ChannelSetupPlanningService>;
        const committer = {
            commitPreparedCandidate: jest.fn().mockResolvedValue({ kind: 'committed', summary: { created: 1, skipped: 0,
                reachedMaxChannels: false, errorCount: 0, canceled: false } }),
        } as unknown as jest.Mocked<ChannelSetupBuildCommitter>;
        const executor = new ChannelSetupBuildExecutor({ channelManager: manager, planningService: planning,
            buildCommitter: committer });
        const choices = config();
        const blocked = await executor.prepareSetupReview(choices);
        expect(blocked.preparedId).toBeUndefined();
        expect(blocked.preview.status).toBe('blocked');

        const review = await executor.prepareSetupReview(choices, { acceptedReadyLibraryIds: ['ready'] });
        expect(review.oldChannelCount).toBeNull();
        expect(review.preview.warnings).toEqual(['Playlist count recovered']);
        expect(review.requiresWholeLineupReplacement).toBe(true);
        expect(review.rows).toHaveLength(1);
        expect(review.rows?.[0]?.channelId).toBeTruthy();
        const id = review.preparedId ?? '';
        const missingConsent = await executor.applySetupReview(id, choices,
            { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: null });
        expect(missingConsent).toMatchObject({ kind: 'blocked', reason: 'consent' });
        expect(committer.commitPreparedCandidate).not.toHaveBeenCalled();

        base = { generation: 2, revision: 4 };
        const stale = await executor.applySetupReview(id, choices,
            { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: id });
        expect(stale).toMatchObject({ kind: 'blocked', reason: 'stale' });
        expect(committer.commitPreparedCandidate).not.toHaveBeenCalled();

        base = { generation: 2, revision: 3 };
        inventoryGeneration = 5;
        expect(await executor.applySetupReview(id, choices,
            { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: id }))
            .toMatchObject({ kind: 'blocked', reason: 'stale' });
        inventoryGeneration = 4;
        scopeKey = JSON.stringify(['u2', 's1']);
        expect(await executor.applySetupReview(id, choices,
            { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: id }))
            .toMatchObject({ kind: 'blocked', reason: 'stale' });
        scopeKey = inventory.scopeKey;
        expect(await executor.applySetupReview(id, { ...choices, minItemsPerChannel: 2 },
            { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: id }))
            .toMatchObject({ kind: 'blocked', reason: 'stale' });
        for (const seriesOrdering of [
            { basePlaybackMode: 'shuffle' as const, baseBlockSize: 3, lineupSeed: 73 },
            { basePlaybackMode: 'shuffle' as const, baseBlockSize: 3, startTimeAnchor: 999 },
            { basePlaybackMode: 'block' as const, baseBlockSize: 3, includeSpecials: false },
        ]) {
            expect(await executor.applySetupReview(id, { ...choices, seriesOrdering },
                { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: id }))
                .toMatchObject({ kind: 'blocked', reason: 'stale' });
        }
        expect(committer.commitPreparedCandidate).not.toHaveBeenCalled();
        const applied = await executor.applySetupReview(id, choices,
            { removalConfirmedForReviewId: id, wholeLineupReplacementConfirmedForReviewId: id });
        expect(applied.kind).toBe('committed');
        const request = committer.commitPreparedCandidate.mock.calls[0]?.[0];
        expect(request?.protectedReplacementHandle).toBe('fresh');
        expect(request?.minItemsPerChannel).toBe(1);
        expect(request?.channels.map((channel) => channel.id)).toEqual(review.rows?.map((row) => row.channelId));
    });

    it('keeps consent bound to the full prepared removal set even if projected rows are changed', async () => {
        const obsolete: ChannelConfig = { ...existing('obsolete', 'ready', 8),
            buildStrategy: 'playlists' as const,
            contentSource: { type: 'playlist' as const, playlistKey: 'obsolete', playlistName: 'Obsolete' } };
        delete obsolete.sourceLibraryId;
        const manager = {
            getStructuralBase: jest.fn(() => ({ generation: 2, revision: 3 })),
            getLastLoadOutcome: jest.fn(() => ({ kind: 'readable', generation: 2, revision: 3, channelCount: 1 })),
            getAllChannels: jest.fn(() => [obsolete]),
            cancelProtectedReplacement: jest.fn(),
        } as unknown as jest.Mocked<IChannelManager>;
        const planning = {
            scanSetupInventory: jest.fn().mockResolvedValue({ ...inventory, sharedPlaylistsStatus: 'ready' }),
            buildAcceptedPlan: jest.fn().mockResolvedValue({ plan: { pendingChannels: [pending],
                estimates: { total: 1 }, warnings: [], skipped: 0, reachedMaxChannels: false }, warnings: [] }),
            get inventoryGeneration() { return 4; },
            getCurrentScopeKey: jest.fn(() => inventory.scopeKey),
            isLibraryInventoryReady: jest.fn(() => true),
        } as unknown as jest.Mocked<ChannelSetupPlanningService>;
        const committer = { commitPreparedCandidate: jest.fn().mockResolvedValue({ kind: 'committed', summary: { created: 1, skipped: 0,
            reachedMaxChannels: false, errorCount: 0, canceled: false } }) } as unknown as jest.Mocked<ChannelSetupBuildCommitter>;
        const executor = new ChannelSetupBuildExecutor({ channelManager: manager, planningService: planning,
            buildCommitter: committer });
        const choices = config();
        const review = await executor.prepareSetupReview(choices, { acceptedReadyLibraryIds: ['ready'] });
        expect(review.rows?.map((row) => row.action)).toEqual(['removed', 'created']);
        if (review.rows?.[0]) review.rows[0].action = 'retained';
        const blocked = await executor.applySetupReview(review.preparedId ?? '', choices,
            { removalConfirmedForReviewId: null, wholeLineupReplacementConfirmedForReviewId: null });
        expect(blocked).toMatchObject({ kind: 'blocked', reason: 'consent' });
        expect(committer.commitPreparedCandidate).not.toHaveBeenCalled();
        await executor.applySetupReview(review.preparedId ?? '', choices,
            { removalConfirmedForReviewId: review.preparedId ?? null, wholeLineupReplacementConfirmedForReviewId: null });
        expect(committer.commitPreparedCandidate.mock.calls[0]?.[0].channels).not.toContainEqual(obsolete);
    });

    it('advances a no-change Review without a structural writer call', async () => {
        const same = existing('same', 'ready', 8);
        const manager = {
            getStructuralBase: jest.fn(() => ({ generation: 2, revision: 3 })),
            getLastLoadOutcome: jest.fn(() => ({ kind: 'readable', generation: 2, revision: 3, channelCount: 1 })),
            getAllChannels: jest.fn(() => [same]),
            cancelProtectedReplacement: jest.fn(),
        } as unknown as jest.Mocked<IChannelManager>;
        const planning = {
            scanSetupInventory: jest.fn().mockResolvedValue(inventory),
            buildAcceptedPlan: jest.fn().mockResolvedValue({ plan: { pendingChannels: [{ ...pending, name: 'same', shuffleSeed: 3 }],
                estimates: { total: 1 }, warnings: [], skipped: 0, reachedMaxChannels: false }, warnings: [] }),
            get inventoryGeneration() { return 4; },
            getCurrentScopeKey: jest.fn(() => inventory.scopeKey),
            isLibraryInventoryReady: jest.fn(() => true),
        } as unknown as jest.Mocked<ChannelSetupPlanningService>;
        const committer = { commitPreparedCandidate: jest.fn() } as unknown as jest.Mocked<ChannelSetupBuildCommitter>;
        const executor = new ChannelSetupBuildExecutor({ channelManager: manager, planningService: planning,
            buildCommitter: committer });
        const choices = config();
        const review = await executor.prepareSetupReview(choices, { acceptedReadyLibraryIds: ['ready'] });
        const result = await executor.applySetupReview(review.preparedId ?? '', choices,
            { removalConfirmedForReviewId: null, wholeLineupReplacementConfirmedForReviewId: null });
        expect(result.kind).toBe('no-change');
        expect(committer.commitPreparedCandidate).not.toHaveBeenCalled();
    });

    it('blocks Review when a full 1–500 append has no free number', async () => {
        const full = Array.from({ length: 500 }, (_, index) => existing(`full-${index}`, 'failed', index + 1));
        const manager = { getStructuralBase: jest.fn(() => ({ generation: 2, revision: 3 })),
            getLastLoadOutcome: jest.fn(() => ({ kind: 'readable' })),
            getAllChannels: jest.fn(() => full) } as unknown as jest.Mocked<IChannelManager>;
        const planning = { scanSetupInventory: jest.fn().mockResolvedValue(inventory),
            buildAcceptedPlan: jest.fn().mockResolvedValue({ plan: { pendingChannels: [pending],
                estimates: { total: 1 }, warnings: [], reachedMaxChannels: false }, warnings: [] }),
            get inventoryGeneration() { return 4; }, getCurrentScopeKey: jest.fn(() => inventory.scopeKey),
            isLibraryInventoryReady: jest.fn(() => true) } as unknown as jest.Mocked<ChannelSetupPlanningService>;
        const committer = { commitPreparedCandidate: jest.fn() } as unknown as jest.Mocked<ChannelSetupBuildCommitter>;
        const executor = new ChannelSetupBuildExecutor({ channelManager: manager, planningService: planning,
            buildCommitter: committer });

        const review = await executor.prepareSetupReview({ ...config(), buildMode: 'append' },
            { acceptedReadyLibraryIds: ['ready'] });
        expect(review.preparedId).toBeUndefined();
        expect(review.preview.message).toContain('No channel numbers');
        expect(committer.commitPreparedCandidate).not.toHaveBeenCalled();
    });
});
