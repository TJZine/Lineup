import { ChannelAuthoringService } from '../../modules/scheduler/channel-manager/authoring/ChannelAuthoringService';
import { cloneChannelForOwnership, cloneContentSource, cloneContentFilters } from '../../modules/scheduler/channel-manager/authoring/ChannelDomainClone';
import { buildDefaultChannelSeed } from '../../modules/scheduler/channel-manager/authoring/ChannelSeedPolicy';
import { isExactAuthoredContentSource } from '../../modules/scheduler/channel-manager/authoring/ChannelContentSourceValidator';
import { MAX_CHANNELS } from '../../modules/scheduler/channel-manager/constants';
import type { ChannelConfig, ChannelContentSource, ChannelCreateInput, ChannelUpdateInput, ChannelClearableField, ContentFilter } from '../../modules/scheduler/channel-manager/contracts/types';
import type { ChannelStructuralBase } from '../../modules/scheduler/channel-manager/contracts/ChannelDurability';
import type { ChannelStudioRequest, StudioDraftKind } from './ChannelStudioContracts';

const sourceIdentity = (source: ChannelContentSource): string => JSON.stringify(source);
function programmingKey(channel: ChannelConfig): string {
    return JSON.stringify({ source: channel.contentSource, mode: channel.playbackMode,
        seed: channel.shuffleSeed, phase: channel.phaseSeed, block: channel.blockSize,
        specials: channel.includeSpecials, anchor: channel.startTimeAnchor,
        anchorMode: channel.scheduleAnchorMode, filters: channel.contentFilters,
        sort: channel.sortOrder, skipIntros: channel.skipIntros, skipCredits: channel.skipCredits,
        maxRuntime: channel.maxEpisodeRunTimeMs, minRuntime: channel.minEpisodeRunTimeMs });
}
const sameBase = (a: ChannelStructuralBase, b: ChannelStructuralBase): boolean => a.generation === b.generation && a.revision === b.revision;

export type DraftIssue = { field: string; message: string };
export type PendingSource = { source: ChannelContentSource; path: number[]; invoker: string };

/** Studio owns one editable in-memory copy. Picker frames never mutate the root until Apply source. */
export class ChannelStudioDraft {
    readonly kind: StudioDraftKind;
    readonly originalId: string | null;
    readonly originalExpectedBase: ChannelStructuralBase;
    readonly original: ChannelConfig | null;
    readonly prospectiveId: string;
    revision = 0;
    channel: ChannelConfig;
    pending: PendingSource[] = [];
    dirty = false;

    private constructor(kind: StudioDraftKind, channel: ChannelConfig, original: ChannelConfig | null,
        base: ChannelStructuralBase, prospectiveId: string) {
        this.kind = kind;
        this.channel = channel;
        this.original = original;
        this.originalId = original?.id ?? null;
        this.originalExpectedBase = { ...base };
        this.prospectiveId = prospectiveId;
    }

    static open(request: ChannelStudioRequest, channels: ChannelConfig[], base: ChannelStructuralBase,
        now: number, prospectiveId: string): ChannelStudioDraft {
        const authoring = new ChannelAuthoringService({ generateId: (): string => prospectiveId, now: (): number => now });
        if (request.kind === 'create') {
            if (channels.length >= MAX_CHANNELS) throw new Error('The lineup already has 500 channels.');
            const number = authoring.getNextAvailableNumber(channels);
            const channel: ChannelConfig = {
                id: prospectiveId, number, name: `Channel ${number}`,
                contentSource: { type: 'manual', items: [] }, playbackMode: 'sequential',
                shuffleSeed: buildDefaultChannelSeed(prospectiveId, 'shuffleSeed'),
                phaseSeed: buildDefaultChannelSeed(prospectiveId, 'phaseSeed'),
                startTimeAnchor: now, skipIntros: false, skipCredits: false,
                createdAt: now, updatedAt: now, lastContentRefresh: 0, itemCount: 0, totalDurationMs: 0,
            };
            return new ChannelStudioDraft('create', channel, null, base, prospectiveId);
        }
        if (!sameBase(base, request.expectedBase)) throw new Error('The lineup changed. Reopen this channel to edit the latest version.');
        const saved = channels.find(channel => channel.id === request.channelId);
        if (!saved) throw new Error('This channel is no longer in the lineup.');
        const original = cloneChannelForOwnership(saved);
        if (request.kind === 'inspect' && (saved.isAutoGenerated || saved.buildStrategy)) {
            return new ChannelStudioDraft('inspect', cloneChannelForOwnership(saved), original, base, prospectiveId);
        }
        if (request.kind === 'duplicate') {
            const number = authoring.getNextAvailableNumber(channels);
            const channel = cloneChannelForOwnership(saved);
            channel.id = prospectiveId; channel.number = number; channel.name = `${saved.name} copy`;
            channel.createdAt = now; channel.updatedAt = now;
            delete channel.isAutoGenerated; delete channel.buildStrategy; delete channel.sourceLibraryId;
            delete channel.sourceLibraryName; delete channel.lineupReplicaIndex; delete channel.isPlaybackModeVariant;
            channel.shuffleSeed = buildDefaultChannelSeed(prospectiveId, 'shuffleSeed');
            channel.phaseSeed = buildDefaultChannelSeed(prospectiveId, 'phaseSeed');
            return new ChannelStudioDraft('duplicate', channel, original, base, prospectiveId);
        }
        return new ChannelStudioDraft('edit', cloneChannelForOwnership(saved), original, base, prospectiveId);
    }

    static fromCommitted(channel: ChannelConfig, base: ChannelStructuralBase, prospectiveId: string): ChannelStudioDraft {
        const saved = cloneChannelForOwnership(channel);
        return new ChannelStudioDraft('edit', cloneChannelForOwnership(saved), saved, base, prospectiveId);
    }

    static replaceSaved(previous: ChannelStudioDraft, saved: ChannelConfig, base: ChannelStructuralBase): ChannelStudioDraft {
        const channel = cloneChannelForOwnership(previous.channel); channel.id = saved.id;
        const draft = new ChannelStudioDraft('edit', channel, cloneChannelForOwnership(saved), base, previous.prospectiveId);
        draft.revision = previous.revision + 1; draft.dirty = true; return draft;
    }

    static refreshNewBase(previous: ChannelStudioDraft, base: ChannelStructuralBase): ChannelStudioDraft {
        const draft = new ChannelStudioDraft(previous.kind, cloneChannelForOwnership(previous.channel), previous.original,
            base, previous.prospectiveId);
        draft.revision = previous.revision + 1; draft.dirty = previous.dirty;
        return draft;
    }

    static saveAsNew(previous: ChannelStudioDraft, peers: ChannelConfig[], base: ChannelStructuralBase,
        now: number, prospectiveId: string): ChannelStudioDraft {
        const authoring = new ChannelAuthoringService({ generateId: (): string => prospectiveId, now: (): number => now });
        const channel = cloneChannelForOwnership(previous.channel);
        channel.id = prospectiveId; channel.number = authoring.getNextAvailableNumber(peers);
        channel.createdAt = now; channel.updatedAt = now;
        channel.shuffleSeed = buildDefaultChannelSeed(prospectiveId, 'shuffleSeed');
        channel.phaseSeed = buildDefaultChannelSeed(prospectiveId, 'phaseSeed');
        delete channel.isAutoGenerated; delete channel.buildStrategy; delete channel.sourceLibraryId;
        delete channel.sourceLibraryName; delete channel.lineupReplicaIndex; delete channel.isPlaybackModeVariant;
        const draft = new ChannelStudioDraft('create', channel, null, base, prospectiveId);
        draft.revision = previous.revision + 1; draft.dirty = true; return draft;
    }

    get editable(): boolean { return this.kind !== 'inspect'; }
    get sourceIdentity(): string { return sourceIdentity(this.channel.contentSource); }
    get isProgrammingDirty(): boolean {
        if (!this.original || this.kind === 'duplicate' || this.kind === 'create') return true;
        return programmingKey(this.original) !== programmingKey(this.channel);
    }

    change(patch: ChannelUpdateInput): void {
        if (!this.editable) return;
        const next = { ...this.channel, ...patch };
        if (patch.contentSource) next.contentSource = cloneContentSource(patch.contentSource);
        if (patch.contentFilters) next.contentFilters = cloneContentFilters(patch.contentFilters);
        this.channel = next;
        this.revision++; this.dirty = true;
    }

    beginSource(source: ChannelContentSource, invoker: string): void {
        if (!this.editable) return;
        this.pending = [{ source: cloneContentSource(source), path: [], invoker }];
    }
    get activeSource(): PendingSource | null { return this.pending.length ? this.pending[this.pending.length - 1] ?? null : null; }
    updatePending(source: ChannelContentSource): void {
        const active = this.activeSource;
        if (active) active.source = cloneContentSource(source);
    }
    enterMixedChild(index: number | 'new', source: ChannelContentSource, invoker: string): void {
        const active = this.activeSource;
        if (!active || active.source.type !== 'mixed') return;
        this.pending.push({ source: cloneContentSource(source), path: [...active.path, index === 'new' ? active.source.sources.length : index], invoker });
    }
    cancelPending(): string | null {
        const active = this.pending.pop();
        return active?.invoker ?? null;
    }
    applyPending(): string | null {
        const active = this.activeSource;
        if (!active || !isExactAuthoredContentSource(active.source)) return null;
        this.pending.pop();
        const parent = this.activeSource;
        if (!parent) { this.change({ contentSource: active.source }); return active.invoker; }
        if (parent.source.type !== 'mixed') return null;
        const index = active.path[active.path.length - 1];
        if (index === undefined) return null;
        const sources = parent.source.sources.map(cloneContentSource);
        if (index === sources.length) sources.push(cloneContentSource(active.source));
        else sources[index] = cloneContentSource(active.source);
        parent.source = { ...parent.source, sources };
        return active.invoker;
    }
    moveMixedChild(index: number, offset: number): void {
        const active = this.activeSource;
        if (!active || active.source.type !== 'mixed') return;
        const to = index + offset;
        if (to < 0 || to >= active.source.sources.length) return;
        const sources = active.source.sources.map(cloneContentSource);
        const moving = sources[index], displaced = sources[to];
        if (!moving || !displaced) return;
        sources[index] = displaced; sources[to] = moving;
        active.source = { ...active.source, sources };
    }
    removeMixedChild(index: number): void {
        const active = this.activeSource;
        if (!active || active.source.type !== 'mixed') return;
        active.source = { ...active.source, sources: active.source.sources.filter((_, i) => i !== index).map(cloneContentSource) };
    }
    setFilters(filters: ContentFilter[]): void { this.change({ contentFilters: cloneContentFilters(filters) }); }
    clearSortOrder(): void {
        if (!this.editable) return;
        const next = { ...this.channel }; delete next.sortOrder;
        this.channel = next; this.revision++; this.dirty = true;
    }

    clearRuntimeBound(field: 'minEpisodeRunTimeMs' | 'maxEpisodeRunTimeMs'): void {
        if (!this.editable) return;
        const next = { ...this.channel }; delete next[field];
        this.channel = next; this.revision++; this.dirty = true;
    }

    validate(peers: ChannelConfig[]): DraftIssue[] {
        const issues: DraftIssue[] = [];
        const ch = this.channel;
        if (!ch.name.trim()) issues.push({ field: 'name', message: 'Enter a channel name.' });
        if (!Number.isInteger(ch.number) || ch.number < 1 || ch.number > 500) issues.push({ field: 'number', message: 'Choose a number from 1 to 500.' });
        else if (peers.some(peer => peer.number === ch.number && peer.id !== this.originalId)) issues.push({ field: 'number', message: 'That number is already used.' });
        if (this.kind !== 'edit' && peers.length >= MAX_CHANNELS) issues.push({ field: 'number', message: 'The lineup already has 500 channels.' });
        if (!isExactAuthoredContentSource(ch.contentSource)) issues.push({ field: 'contentSource', message: 'Choose a complete source and apply it.' });
        if (ch.scheduleAnchorMode === 'fixed' && !Number.isFinite(ch.startTimeAnchor)) issues.push({ field: 'startTimeAnchor', message: 'Enter a valid fixed start time.' });
        if (ch.playbackMode === 'block' && (!Number.isInteger(ch.blockSize ?? 3) || (ch.blockSize ?? 3) < 1)) issues.push({ field: 'blockSize', message: 'Choose a positive block size.' });
        if (ch.minEpisodeRunTimeMs !== undefined && (!Number.isFinite(ch.minEpisodeRunTimeMs) || ch.minEpisodeRunTimeMs < 0))
            issues.push({ field: 'minEpisodeRunTimeMs', message: 'Minimum duration must be zero or greater.' });
        if (ch.maxEpisodeRunTimeMs !== undefined && (!Number.isFinite(ch.maxEpisodeRunTimeMs) || ch.maxEpisodeRunTimeMs <= 0))
            issues.push({ field: 'maxEpisodeRunTimeMs', message: 'Maximum duration must be greater than zero.' });
        if (ch.minEpisodeRunTimeMs !== undefined && ch.maxEpisodeRunTimeMs !== undefined
            && ch.maxEpisodeRunTimeMs < ch.minEpisodeRunTimeMs)
            issues.push({ field: 'maxEpisodeRunTimeMs', message: 'Maximum duration must be at least the minimum.' });
        try {
            const authoring = new ChannelAuthoringService({ generateId: (): string => this.prospectiveId, now: (): number => ch.updatedAt });
            if (this.kind === 'edit' && this.original) authoring.updateChannel(this.original, this.toUpdateInput(), peers.filter(peer => peer.id !== this.originalId));
            else if (this.kind !== 'inspect') authoring.createChannel(this.toCreateInput(), peers);
        } catch (error) { issues.push({ field: 'channel', message: error instanceof Error ? error.message : 'Invalid channel details.' }); }
        return issues;
    }

    toCreateInput(): ChannelCreateInput {
        const ch = this.channel;
        return {
            number: ch.number, name: ch.name,
            ...(ch.description !== undefined ? { description: ch.description } : {}),
            ...(ch.icon !== undefined ? { icon: ch.icon } : {}),
            contentSource: cloneContentSource(ch.contentSource), playbackMode: ch.playbackMode,
            ...(ch.shuffleSeed !== undefined ? { shuffleSeed: ch.shuffleSeed } : {}),
            ...(ch.phaseSeed !== undefined ? { phaseSeed: ch.phaseSeed } : {}),
            ...(ch.blockSize !== undefined ? { blockSize: ch.blockSize } : {}),
            ...(ch.includeSpecials !== undefined ? { includeSpecials: ch.includeSpecials } : {}),
            startTimeAnchor: ch.startTimeAnchor,
            ...(ch.scheduleAnchorMode !== undefined ? { scheduleAnchorMode: ch.scheduleAnchorMode } : {}),
            ...(ch.contentFilters !== undefined ? { contentFilters: cloneContentFilters(ch.contentFilters) } : {}),
            ...(ch.sortOrder !== undefined ? { sortOrder: ch.sortOrder } : {}),
            skipIntros: ch.skipIntros, skipCredits: ch.skipCredits,
            ...(ch.maxEpisodeRunTimeMs !== undefined ? { maxEpisodeRunTimeMs: ch.maxEpisodeRunTimeMs } : {}),
            ...(ch.minEpisodeRunTimeMs !== undefined ? { minEpisodeRunTimeMs: ch.minEpisodeRunTimeMs } : {}),
        };
    }
    toUpdateInput(): ChannelUpdateInput {
        const clearFields: ChannelClearableField[] = [];
        for (const field of ['sortOrder', 'minEpisodeRunTimeMs', 'maxEpisodeRunTimeMs'] as const) {
            if (this.original?.[field] !== undefined && this.channel[field] === undefined) clearFields.push(field);
        }
        return { ...this.toCreateInput(), ...(clearFields.length ? { clearFields } : {}) };
    }
}
