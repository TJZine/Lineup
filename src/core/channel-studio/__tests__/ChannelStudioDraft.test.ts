import { ChannelAuthoringService } from '../../../modules/scheduler/channel-manager/authoring/ChannelAuthoringService';
import { createBaseChannel } from '../../../modules/scheduler/channel-manager/__tests__/channel-manager-test-helpers';
import type { ChannelConfig, ChannelContentSource } from '../../../modules/scheduler/channel-manager/contracts/types';
import { ChannelStudioDraft } from '../ChannelStudioDraft';

const base = { generation: 2, revision: 7 };
const movie: ChannelContentSource = { type: 'library', libraryId: 'movies', libraryType: 'movie', includeWatched: false };
const playlist: ChannelContentSource = { type: 'playlist', playlistKey: 'p1', playlistName: 'Favorites' };
const manual: ChannelContentSource = { type: 'manual', items: [
    { ratingKey: 'm1', title: 'A', durationMs: 60_000 }, { ratingKey: 'm1', title: 'A', durationMs: 60_000 },
] };
const saved = createBaseChannel({ id: 'saved', number: 8, name: 'Saved', contentSource: {
    type: 'mixed', mixMode: 'interleave', sources: [movie, { type: 'mixed', mixMode: 'sequential', sources: [playlist, manual] }],
}, playbackMode: 'random', shuffleSeed: 44, phaseSeed: 45, scheduleAnchorMode: 'fixed', startTimeAnchor: 1234 });

describe('ChannelStudioDraft', () => {
    it('reopens every authored nested source, mode, seed and anchor without flattening', () => {
        const draft = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'saved', expectedBase: base }, [saved], base, 9000, 'prospective');
        expect(draft.kind).toBe('edit');
        expect(draft.channel).toEqual(saved);
        expect(draft.channel.contentSource).not.toBe(saved.contentSource);
        expect(draft.validate([saved])).toEqual([]);
    });

    it('keeps a pending recursive child isolated until each Apply, and Cancel restores the parent', () => {
        const draft = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'saved', expectedBase: base }, [saved], base, 9000, 'prospective');
        draft.beginSource(draft.channel.contentSource, 'source-button');
        const root = draft.activeSource?.source;
        if (root?.type !== 'mixed') throw new Error('expected mixed');
        draft.enterMixedChild(1, root.sources[1]!, 'nested-button');
        const nested = draft.activeSource?.source;
        if (nested?.type !== 'mixed') throw new Error('expected nested mixed');
        draft.enterMixedChild(1, nested.sources[1]!, 'manual-button');
        draft.updatePending({ type: 'manual', items: [
            ...manual.items, { ratingKey: 'm2', title: 'B', durationMs: 120_000 },
        ] });
        expect(draft.cancelPending()).toBe('manual-button');
        expect((draft.activeSource?.source as Extract<ChannelContentSource, { type: 'mixed' }>).sources[1]).toEqual(manual);
        draft.enterMixedChild(1, manual, 'manual-button');
        draft.updatePending({ type: 'manual', items: [manual.items[0]!] });
        expect(draft.applyPending()).toBe('manual-button');
        expect(draft.applyPending()).toBe('nested-button');
        expect(draft.channel.contentSource).toEqual(saved.contentSource);
        expect(draft.applyPending()).toBe('source-button');
        expect((draft.channel.contentSource as Extract<ChannelContentSource, { type: 'mixed' }>).sources[1]).toEqual({
            type: 'mixed', mixMode: 'sequential', sources: [playlist, { type: 'manual', items: [manual.items[0]!] }],
        });
        expect(saved.contentSource).toEqual(createBaseChannel({ contentSource: saved.contentSource }).contentSource);
    });

    it('moves a duplicate occurrence without merging it and strips generated provenance from a custom copy', () => {
        const generated: ChannelConfig = { ...saved, isAutoGenerated: true, buildStrategy: 'collections', sourceLibraryId: 'movies',
            sourceLibraryName: 'Movies', lineupReplicaIndex: 1, isPlaybackModeVariant: true };
        const duplicate = ChannelStudioDraft.open({ kind: 'duplicate', channelId: 'saved', expectedBase: base }, [generated], base, 9000, 'copy-id');
        expect(duplicate.channel.number).toBe(1);
        expect(duplicate.channel.isAutoGenerated).toBeUndefined();
        expect(duplicate.channel.buildStrategy).toBeUndefined();
        const nested = (duplicate.channel.contentSource as Extract<ChannelContentSource, { type: 'mixed' }>).sources[1] as Extract<ChannelContentSource, { type: 'mixed' }>;
        expect((nested.sources[1] as Extract<ChannelContentSource, { type: 'manual' }>).items.map(item => item.ratingKey)).toEqual(['m1', 'm1']);
        expect(duplicate.toCreateInput().shuffleSeed).toBe(duplicate.channel.shuffleSeed);
        expect(duplicate.toCreateInput().phaseSeed).toBe(duplicate.channel.phaseSeed);
    });
    it.each([
        { type: 'library', libraryId: 'movies', libraryType: 'movie', includeWatched: true },
        { type: 'collection', collectionKey: 'c1', collectionName: 'Collection' },
        { type: 'show', showKey: 's1', showName: 'Show', seasonFilter: [1, 2] },
        { type: 'playlist', playlistKey: 'p1', playlistName: 'Playlist' },
        { type: 'manual', items: [{ ratingKey: 'm1', title: 'Movie', durationMs: 60_000 }] },
        { type: 'mixed', mixMode: 'sequential', sources: [movie, playlist] },
    ] as ChannelContentSource[])('preserves the %s source through edit input', source => {
        const channel = createBaseChannel({ ...saved, contentSource: source, contentFilters: [
            { field: 'year', operator: 'gte', value: 1980 }, { field: 'genre', operator: 'contains', value: 'Drama' },
        ] });
        const draft = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'saved', expectedBase: base }, [channel], base, 9000, 'prospective');
        expect(draft.validate([channel])).toEqual([]);
        expect(draft.toUpdateInput().contentSource).toEqual(source);
        expect(draft.toUpdateInput().contentFilters).toEqual(channel.contentFilters);
        const authoring = new ChannelAuthoringService({ generateId: (): string => 'reopened', now: (): number => 9100 });
        const persisted = authoring.createChannel(draft.toCreateInput(), []);
        const reopened = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'reopened', expectedBase: base },
            [persisted], base, 9200, 'next');
        expect(reopened.channel.contentSource).toEqual(source);
        expect(reopened.channel.contentFilters).toEqual(channel.contentFilters);
    });

    it.each(['sequential', 'shuffle', 'block', 'random'] as const)('retains %s playback with seed and explicit anchor', mode => {
        const channel = createBaseChannel({ ...saved, playbackMode: mode, blockSize: 3,
            includeSpecials: false, shuffleSeed: 18, phaseSeed: 19, scheduleAnchorMode: 'fixed', startTimeAnchor: 1234 });
        const draft = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'saved', expectedBase: base }, [channel], base, 9000, 'prospective');
        const input = draft.toUpdateInput();
        expect(input).toEqual(expect.objectContaining({ playbackMode: mode, shuffleSeed: 18, phaseSeed: 19,
            blockSize: 3, includeSpecials: false, scheduleAnchorMode: 'fixed', startTimeAnchor: 1234 }));
    });
    it('freezes create seeds and anchor before manager assigns its durable ID', () => {
        const draft = ChannelStudioDraft.open({ kind: 'create' }, [], base, 9000, 'preview-id');
        draft.change({ contentSource: manual, playbackMode: 'random', scheduleAnchorMode: 'fixed', startTimeAnchor: 8000 });
        const input = draft.toCreateInput();
        const service = new ChannelAuthoringService({ generateId: (): string => 'durable-id', now: (): number => 9100 });
        const persisted = service.createChannel(input, []);
        expect(persisted.id).toBe('durable-id');
        expect(persisted.shuffleSeed).toBe(draft.channel.shuffleSeed);
        expect(persisted.phaseSeed).toBe(draft.channel.phaseSeed);
        expect(persisted.scheduleAnchorMode).toBe('fixed');
        expect(persisted.startTimeAnchor).toBe(8000);
        expect(persisted.contentSource).toEqual(manual);
    });
    it('saves and reopens an explicit specials-only Show season selection', () => {
        const draft = ChannelStudioDraft.open({ kind: 'create' }, [], base, 9000, 'preview-id');
        draft.change({ contentSource: { type: 'show', showKey: 'show-1', showName: 'Series', seasonFilter: [0] },
            playbackMode: 'sequential', sortOrder: 'episode_order' });
        expect(draft.validate([])).toEqual([]);
        const authoring = new ChannelAuthoringService({ generateId: (): string => 'saved-specials', now: (): number => 9100 });
        const persisted = authoring.createChannel(draft.toCreateInput(), []);
        expect(persisted.contentSource).toEqual({ type: 'show', showKey: 'show-1', showName: 'Series', seasonFilter: [0] });
        const reopened = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'saved-specials', expectedBase: base },
            [persisted], base, 9200, 'next-id');
        expect(reopened.channel.contentSource).toEqual(persisted.contentSource);
        expect(reopened.validate([persisted])).toEqual([]);
    });
    it('saves and reopens Collection type and library scope at nested Mixed depth', () => {
        const collection: ChannelContentSource = { type: 'collection', collectionKey: 'c-show', collectionName: 'Series picks',
            libraryId: 'shows', libraryType: 'show', libraryName: 'TV Library' };
        const source: ChannelContentSource = { type: 'mixed', mixMode: 'sequential', sources: [movie,
            { type: 'mixed', mixMode: 'interleave', sources: [collection, playlist] }] };
        const draft = ChannelStudioDraft.open({ kind: 'create' }, [], base, 9000, 'preview-id');
        draft.change({ contentSource: source });
        expect(draft.validate([])).toEqual([]);
        const authoring = new ChannelAuthoringService({ generateId: (): string => 'nested-collection', now: (): number => 9100 });
        const persisted = authoring.createChannel(draft.toCreateInput(), []);
        const reopened = ChannelStudioDraft.open({ kind: 'inspect', channelId: 'nested-collection', expectedBase: base },
            [persisted], base, 9200, 'next-id');
        expect(reopened.channel.contentSource).toEqual(source);
        expect(reopened.validate([persisted])).toEqual([]);
    });
});
